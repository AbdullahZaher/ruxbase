// ValidateExposedTableName checks that a candidate table name is safe and valid for API exposure.
func ValidateExposedTableName(tableName string) error {
	name := strings.TrimSpace(tableName)
	if name == "" {
		return errors.New("table name cannot be empty")
	}

	// Prevent exposing internal/system collections
	if strings.HasPrefix(name, "_") {
		return fmt.Errorf("cannot expose internal system table %q", name)
	}

	lower := strings.ToLower(name)
	if strings.HasPrefix(lower, "pg_") || strings.HasPrefix(lower, "information_schema.") ||
		strings.HasPrefix(lower, "information_schema") {
		return fmt.Errorf("cannot expose PostgreSQL system catalog table %q", name)
	}

	// Validate character set (alphanumeric and underscore only)
	for _, ch := range name {
		if (ch < 'a' || ch > 'z') && (ch < 'A' || ch > 'Z') && (ch < '0' || ch > '9') && ch != '_' {
			return fmt.Errorf("table name %q contains invalid characters; only alphanumeric and underscores allowed", name)
		}
	}

	return nil
}

// ExposeTableOptions defines parameters for exposing an existing native PostgreSQL table.
type ExposeTableOptions struct {
	TableName       string   `json:"tableName"`
	CollectionName  string   `json:"collectionName"`
	ListRule        *string  `json:"listRule"`
	ViewRule        *string  `json:"viewRule"`
	CreateRule      *string  `json:"createRule"`
	UpdateRule      *string  `json:"updateRule"`
	DeleteRule      *string  `json:"deleteRule"`
	ExcludedColumns []string `json:"excludedColumns"`
}

// NativeTableSummary provides high-level status of a candidate native PostgreSQL table.
type NativeTableSummary struct {
	Schema           string `json:"schema"`
	Name             string `json:"name"`
	Kind             string `json:"kind"` // 'r' table, 'v' view, 'm' matview, 'p' partition
	Owner            string `json:"owner"`
	IsExposed        bool   `json:"isExposed"`
	CollectionId     string `json:"collectionId,omitempty"`
	HasPrimaryKey    bool   `json:"hasPrimaryKey"`
	RowSecurity      bool   `json:"rowSecurity"`
	ForceRowSecurity bool   `json:"forceRowSecurity"`
}

// ListExposableTables returns summaries of all candidate native tables in the specified schema.
func (app *BaseApp) ListExposableTables(schema string) ([]*NativeTableSummary, error) {
	if schema == "" {
		schema = "public"
	}

	tables, err := app.IntrospectSchemaTables(schema)
	if err != nil {
		return nil, err
	}

	// Query existing collection names
	collections, err := app.FindAllCollections(CollectionTypeBase, CollectionTypeAuth, CollectionTypeView)
	if err != nil {
		return nil, err
	}
	exposedMap := make(map[string]*Collection, len(collections))
	for _, col := range collections {
		exposedMap[strings.ToLower(col.Name)] = col
	}

	summaries := make([]*NativeTableSummary, 0, len(tables))
	for _, tbl := range tables {
		// Filter out internal tables starting with underscore
		if strings.HasPrefix(tbl.Name, "_") {
			continue
		}

		// Quick check for primary key
		var hasPK bool
		var pkCount int
		_ = app.ConcurrentDB().NewQuery(`
			SELECT COUNT(*)
			FROM {{pg_index}} i
			WHERE i.[[indrelid]] = to_regclass(quote_ident({:tableName})) AND i.[[indisprimary]]
		`).Bind(map[string]any{"tableName": tbl.Name}).Row(&pkCount)
		hasPK = pkCount > 0

		col, isExposed := exposedMap[strings.ToLower(tbl.Name)]

		summary := &NativeTableSummary{
			Schema:           tbl.Schema,
			Name:             tbl.Name,
			Kind:             tbl.Kind,
			Owner:            tbl.Owner,
			IsExposed:        isExposed,
			HasPrimaryKey:    hasPK,
			RowSecurity:      tbl.RowSecurity,
			ForceRowSecurity: tbl.ForceRowSecurity,
		}
		if col != nil {
			summary.CollectionId = col.Id
		}

		summaries = append(summaries, summary)
	}

	return summaries, nil
}

// IntrospectAndBuildCollection inspects an existing native table and constructs a candidate Collection.
// All access rules default to nil (deny-by-default).
func (app *BaseApp) IntrospectAndBuildCollection(tableName string) (*Collection, error) {
	if err := ValidateExposedTableName(tableName); err != nil {
		return nil, err
	}

	tbl, err := app.IntrospectTable(tableName)
	if err != nil {
		return nil, err
	}

	if len(tbl.Columns) == 0 {
		return nil, fmt.Errorf("native table %q has no accessible columns", tableName)
	}

	collection := NewBaseCollection(tableName)
	// Clear default fields generated by NewBaseCollection to populate purely from native columns
	collection.Fields = FieldsList{}

	fkByCol := make(map[string]*NativeConstraint)
	for _, fk := range tbl.ForeignKeys() {
		for _, colName := range fk.Columns {
			fkByCol[strings.ToLower(colName)] = fk
		}
	}

	var hasIdField bool
	for _, col := range tbl.Columns {
		// If column is backed by a native Foreign Key, map to RelationField
		if fk, ok := fkByCol[strings.ToLower(col.Name)]; ok && fk.RefTable != "" {
			targetCol, _ := app.FindCollectionByNameOrId(fk.RefTable)
			targetId := fk.RefTable
			if targetCol != nil {
				targetId = targetCol.Id
			}

			relField := &RelationField{
				Id:            security.PseudorandomString(8),
				Name:          col.Name,
				CollectionId:  targetId,
				Required:      !col.Nullable(),
				NativeFK:      true,
				CascadeDelete: fk.OnDelete == "CASCADE",
				OnDelete:      fk.OnDelete,
				OnUpdate:      fk.OnUpdate,
				MaxSelect:     1,
			}
			collection.Fields.Add(relField)
			continue
		}

		field, err := MapNativeColumnToField(col)
		if err != nil {
			return nil, fmt.Errorf("failed to map column %q: %w", col.Name, err)
		}

		if strings.EqualFold(col.Name, FieldNameId) {
			hasIdField = true
			if tf, ok := field.(*TextField); ok {
				tf.PrimaryKey = true
				if tf.Pattern == "" {
					tf.Pattern = DefaultIdRegex.String()
				}
			}
		}

		collection.Fields.Add(field)
	}

	// If no 'id' column exists, initialize default id field for PocketBase API compatibility
	if !hasIdField {
		collection.initIdField()
	}

	// Strict Deny-by-Default: All access rules remain nil
	collection.ListRule = nil
	collection.ViewRule = nil
	collection.CreateRule = nil
	collection.UpdateRule = nil
	collection.DeleteRule = nil

	return collection, nil
}

// ExposeNativeTable registers an existing native PostgreSQL table as an exposed Collection.
func (app *BaseApp) ExposeNativeTable(opts ExposeTableOptions) (*Collection, error) {
	if err := ValidateExposedTableName(opts.TableName); err != nil {
		return nil, err
	}

	colName := strings.TrimSpace(opts.CollectionName)
	if colName == "" {
		colName = opts.TableName
	}

	// Check if already exposed
	existing, _ := app.FindCollectionByNameOrId(colName)
	if existing != nil {
		return nil, fmt.Errorf("collection %q already exists", colName)
	}

	collection, err := app.IntrospectAndBuildCollection(opts.TableName)
	if err != nil {
		return nil, err
	}

	collection.Name = colName

	// Filter out any excluded columns
	if len(opts.ExcludedColumns) > 0 {
		filteredFields := FieldsList{}
		for _, field := range collection.Fields {
			if !list.ExistInSlice(field.GetName(), opts.ExcludedColumns) {
				filteredFields.Add(field)
			}
		}
		collection.Fields = filteredFields
	}

	// Apply explicit access rules
	collection.ListRule = opts.ListRule
	collection.ViewRule = opts.ViewRule
	collection.CreateRule = opts.CreateRule
	collection.UpdateRule = opts.UpdateRule
	collection.DeleteRule = opts.DeleteRule

	// Save collection into database catalog (automatically compiles RLS policies and enables RLS)
	if err := app.Save(collection); err != nil {
		return nil, fmt.Errorf("failed to save exposed collection: %w", err)
	}

	return collection, nil
}

// TableExposureInfo contains exposure status and access rules for a table.
type TableExposureInfo struct {
	TableName  string  `json:"tableName"`
	IsExposed  bool    `json:"isExposed"`
	AccessRule *string `json:"accessRule,omitempty"`
	CreateRule *string `json:"createRule,omitempty"`
	UpdateRule *string `json:"updateRule,omitempty"`
	DeleteRule *string `json:"deleteRule,omitempty"`
}

// GetTableExposure retrieves the exposure status and access rules for a table.
func (app *BaseApp) GetTableExposure(tableName string) (*TableExposureInfo, error) {
	col, err := app.FindCollectionByNameOrId(tableName)
	if err != nil || col == nil {
		return &TableExposureInfo{
			TableName: tableName,
			IsExposed: false,
		}, nil
	}

	return &TableExposureInfo{
		TableName:  col.Name,
		IsExposed:  true,
		AccessRule: col.ListRule,
		CreateRule: col.CreateRule,
		UpdateRule: col.UpdateRule,
		DeleteRule: col.DeleteRule,
	}, nil
}
